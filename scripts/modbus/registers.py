# -*- coding: utf-8 -*-
"""Карта используемых Modbus-регистров контроллера стенда SPG-023MK.

Раньше адреса были магическими числами, разбросанными по
thread_reader.py/thread_writer.py/model.py — собраны здесь в одном месте,
чтобы протокол было проще сверять и менять.

Расшифровка битов слова состояния/входного модуля — в
scripts/parser/parser.py (ParserSPG023MK._register_state/_switch_state).
"""

# "Живой" блок состояния: усилие, перемещение, слово состояния, температуры,
# счётчик записи и т.д. — читается непрерывно, пока не идёт запись в буфер.
REG_STATE_BLOCK = 0x2000
REG_STATE_BLOCK_COUNT = 14

# Слово состояния/команд (запись отдельных бит — см. Model._write_reg_state)
REG_STATE_WORD = 0x2003

# Аварийное (максимально допустимое) усилие — запись при старте испытания
REG_EMERGENCY_FORCE = 0x200a

# "Почтовый ящик" команд частотным преобразователям: контроллер стенда
# ретранслирует записанный сюда Modbus-RTU-кадр (адрес ЧП, команда, CRC16)
# дальше на шину ЧП. Перед командой пишется её длина в REG_FC_COMMAND_LEN.
REG_FC_COMMAND_LEN = 0x2060
REG_FC_COMMAND = 0x2061

# Кольцевой буфер осциллограммы испытания, читается пачками во время теста
REG_BUFFER_START = 0x4000
REG_BUFFER_RECORD_REGS = 6        # регистров на одну запись буфера
REG_BUFFER_RECORDS_PER_READ = 20  # записей за одно чтение (по умолчанию)
REG_BUFFER_TOTAL_REGS = 18000     # общий размер буфера в регистрах (3000 записей)
